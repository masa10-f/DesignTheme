def _status(result: Optional[tl.ContrastResult]) -> str:
    if result is None:
        return "surface"
    ratio = tl.format_ratio(result.ratio)
    return {
        "decorative": f"{ratio} decorative",
        "fail": f"{ratio} below threshold",
        "graphic-only": f"{ratio} lines only",
    }.get(result.status, f"{ratio} OK")


