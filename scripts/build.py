def _contrast_cell(result: Optional[tl.ContrastResult]) -> str:
    if result is None:
        return "—"
    ratio = tl.format_ratio(result.ratio)
    vs = f"vs `{result.against}`"
    status = result.status
    if status == "fail":
        return f"**{ratio}** {vs} ⚠ 基準未満"
    if status == "graphic-only":
        return f"{ratio} {vs} ✓ 線・図形 / ⚠ 文字には不可"
    if status == "decorative":
        return f"{ratio} {vs}"
    return f"{ratio} {vs} ✓"


def _origin(theme: tl.Theme, name: str) -> str:
    """palette の色がどこから来たか（README 用）。"""
    entry = theme.data["palette"][name]
    for key, seed_name in theme.seeds.items():
        if seed_name == name:
            return f"種色（{tl.SEED_JA[key]}）"
    derived = entry.get("derived")
    if derived is None:
        return "固定"
    if "from" in derived:
        chroma = f"・彩度 {derived['chroma']:g}" if "chroma" in derived else ""
        return f"`{derived['from']}` の色相{chroma}・明度 {derived['tone']}"
    return f"追加色（色相 {derived['hue']:g}°・彩度 {derived['chroma']:g}・明度 {derived['tone']}）"


def _seed_ratio(ratio: float) -> str:
    if ratio >= tl.TEXT_MIN:
        verdict = "文字 ✓"
    elif ratio >= tl.GRAPHIC_MIN:
        verdict = "線・図形 ✓ / 文字 ✗"
    else:
        verdict = "⚠ 文字・線とも ✗"
    return f"{tl.format_ratio(ratio)}（{verdict}）"


def _seed_rows(theme: tl.Theme) -> List[str]:
    palette = theme.palette_hex()
    band = theme.role_hex()["band"]
    uses: Dict[str, List[str]] = {}
    for role, spec in theme.roles.items():
        uses.setdefault(spec["color"], []).append(f"`{role}`")
    for i, n in enumerate(theme.series_names):
        uses.setdefault(n, []).append(f"系列 {i + 1}")
    checks = {c.key: c for c in tl.seed_checks(theme.seeds, {k: palette[n] for k, n in theme.seeds.items()})}
    rows = [
        "| 種色 | palette | hex | 明度 L* | 種色の基準 | 白地（`background`） | 帯（`band`）の上 | そのまま使う場所 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for key in tl.SEED_KEYS:
        n = theme.seeds[key]
        h = palette[n]
        on_band = "—" if theme.roles["band"]["color"] == n else _seed_ratio(cl.contrast_ratio(h, band))
        rows.append(
            f"| {tl.SEED_JA[key]} | `{n}` | `{h}` | {cl.tone(h):.1f} | {_seed_criterion(checks[key])} "
            f"| {_seed_ratio(cl.contrast_ratio(h, '#FFFFFF'))} | {on_band} | {'、'.join(uses.get(n, [])) or '—'} |"
        )
    return rows


def _seed_criterion(check: tl.SeedCheck) -> str:
    """種色の基準（docs/color-theory.md）の判定。満たさなければ提案の色も示す。"""
    target = {"base": "白か本文色の文字に", "accent": "白地で", "sub": "帯の上で"}[check.key]
    head = f"{target} {check.minimum:g}:1 以上"
    if check.ok:
        return f"✓ {head}"
    if check.proposal_hex is None:
        return f"⚠ {head}（{tl.format_ratio(check.ratio)}）"
    return f"⚠ {head}（{tl.format_ratio(check.ratio)}）。提案 `{check.proposal_hex}`（明度 {check.proposal_tone}）"


