#!/usr/bin/env python3
"""themes/*/theme.json から dist/<番号>/ と README.md のテーマ一覧を生成する。

使い方:
  python scripts/build.py           # 生成して書き込む（dist/ 内の不要なファイルは削除）
  python scripts/build.py --check   # 書き込まずに、生成結果とリポジトリの内容が一致するか確かめる

出力は入力だけで決まる（日時などを含めない）ので、2回実行しても差分は出ない。
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional
from xml.sax.saxutils import escape as xml_escape

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check  # noqa: E402
import themelib as tl  # noqa: E402

# theme-colors.sty の \ProvidesPackage に書く日付。LaTeX は版情報の先頭を日付として読むので必須。
# 出力を決定的にするため、ビルド時刻ではなく生成形式の版として固定する（形式を変えたら更新する）。
STY_FORMAT_DATE = "2026/11/06"

README_BEGIN = "<!-- BEGIN GENERATED: themes -->"
README_END = "<!-- END GENERATED: themes -->"
TOKEN_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")

CHART_STATUS_JA = {"provisional": "暫定案・要確認", "confirmed": "確定"}
KIND_JA = {
    "text": "文字 4.5:1",
    "large-text": "大きい文字 3:1",
    "graphic": "線・図形 3:1",
    "decorative": "装飾（対象外）",
    "surface": "面",
}


class BuildError(Exception):
    pass


def _src(theme: tl.Theme, root: Path) -> str:
    return theme.path.relative_to(root).as_posix()


def _header(theme: tl.Theme, root: Path) -> List[str]:
    return [
        f"Theme {theme.id} {theme.name} ({theme.slug}), status: {theme.status}",
        f"Generated by scripts/build.py from {_src(theme, root)}. Do not edit by hand.",
    ]


def _json(data: object) -> str:
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


# --------------------------------------------------------------------------- per-format renderers


def render_css(theme: tl.Theme, root: Path) -> str:
    typo = theme.typography
    latin = [typo["latin"], *typo["fallbacks"]["latin"]]
    east_asian = [typo["east_asian"], *typo["fallbacks"]["east_asian"]]
    lines = [f"/* {line} */" for line in _header(theme, root)]
    lines.append(":root {")
    lines.append("  /* roles: スタイルではこれを使う */")
    lines += [f"  --color-{role}: {hex_};" for role, hex_ in theme.role_hex().items()]
    if theme.series_names:
        lines.append(f"  /* chart.series ({theme.chart_status}: {CHART_STATUS_JA[theme.chart_status]}) */")
        lines += [f"  --chart-series-{i}: {hex_};" for i, hex_ in enumerate(theme.series_hex(), start=1)]
    lines.append("  /* palette: 生の色（直接使わず roles を使う） */")
    lines += [f"  --palette-{name}: {hex_};" for name, hex_ in theme.palette_hex().items()]
    lines.append("  /* typography */")
    lines.append(f"  --font-latin: {tl.css_font_family(latin)};")
    lines.append(f"  --font-east-asian: {tl.css_font_family(east_asian)};")
    lines.append(f"  --font-sans: {tl.css_font_family(tl.font_stack(typo))};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_tokens_json(theme: tl.Theme, root: Path) -> str:
    typo = theme.typography
    return _json(
        {
            "id": theme.id,
            "slug": theme.slug,
            "name": theme.name,
            "status": theme.status,
            "generated_from": _src(theme, root),
            "roles": theme.role_hex(),
            "palette": theme.palette_hex(),
            "chart": {"status": theme.chart_status, "series": theme.series_hex()},
            "fonts": {
                "latin": typo["latin"],
                "east_asian": typo["east_asian"],
                "family": tl.font_stack(typo),
            },
        }
    )


def render_mplstyle(theme: tl.Theme, root: Path) -> str:
    # matplotlib のスタイルファイルでは '#' がコメントなので、色は '#' なしで書く。ASCII のみにする。
    c = {role: hex_.lstrip("#") for role, hex_ in theme.role_hex().items()}
    lines = [f"# {line}" for line in _header(theme, root)]
    lines += [
        "# Colors: roles text / text-secondary / background. Color cycle: chart.series",
        f"# chart.series status: {theme.chart_status}"
        + (" (tentative proposal, needs review)" if theme.chart_status == "provisional" else ""),
        "",
    ]
    if theme.series_names:
        cycle = ", ".join(f"'{h.lstrip('#')}'" for h in theme.series_hex())
        lines += [f"axes.prop_cycle: cycler('color', [{cycle}])", ""]
    lines += [
        f"figure.facecolor: {c['background']}",
        f"axes.facecolor: {c['background']}",
        f"savefig.facecolor: {c['background']}",
        "",
        f"text.color: {c['text']}",
        f"axes.labelcolor: {c['text']}",
        f"axes.titlecolor: {c['text']}",
        f"xtick.labelcolor: {c['text']}",
        f"ytick.labelcolor: {c['text']}",
        "",
        f"axes.edgecolor: {c['text-secondary']}",
        f"xtick.color: {c['text-secondary']}",
        f"ytick.color: {c['text-secondary']}",
        "",
        "# Latin font first, then East Asian; matplotlib >= 3.6 falls back per glyph along this list.",
        f"font.family: {', '.join(tl.font_stack(theme.typography))}",
    ]
    return "\n".join(lines) + "\n"


def render_python(theme: tl.Theme, root: Path) -> str:
    def s(value: str) -> str:
        return json.dumps(value, ensure_ascii=False)

    def mapping(name: str, data: Dict[str, str]) -> List[str]:
        return [f"{name} = {{", *[f"    {s(k)}: {s(v)}," for k, v in data.items()], "}"]

    typo = theme.typography
    header = _header(theme, root)
    lines = ['"""' + header[0] + ".", "", header[1], '"""', ""]
    lines += [
        f"THEME_ID = {s(theme.id)}",
        f"THEME_SLUG = {s(theme.slug)}",
        f"THEME_NAME = {s(theme.name)}",
        f"THEME_STATUS = {s(theme.status)}",
        "",
        "# role 名 → hex。コードではこれを使う。",
    ]
    lines += mapping("COLORS", theme.role_hex())
    lines += ["", f"# グラフの系列色（chart.series）。状態: {theme.chart_status}（{CHART_STATUS_JA[theme.chart_status]}）"]
    lines += ["CHART_SERIES = [", *[f"    {s(h)}," for h in theme.series_hex()], "]"]
    lines += [f"CHART_SERIES_STATUS = {s(theme.chart_status)}", ""]
    lines += ["# palette 名 → hex（生の色。直接使わず COLORS を使う）"]
    lines += mapping("PALETTE", theme.palette_hex())
    lines += [
        "",
        f"FONT_LATIN = {s(typo['latin'])}",
        f"FONT_EAST_ASIAN = {s(typo['east_asian'])}",
        "# 欧文 → 和文 → 代替の順（matplotlib の font.family などに渡す）",
        "FONT_FAMILY = [" + ", ".join(s(n) for n in tl.font_stack(typo)) + "]",
    ]
    return "\n".join(lines) + "\n"


def render_sty(theme: tl.Theme, root: Path) -> str:
    def define(name: str, hex_: str) -> str:
        return f"\\definecolor{{{name}}}{{HTML}}{{{hex_.lstrip('#')}}}"

    typo = theme.typography
    for font in (typo["latin"], typo["east_asian"]):
        if re.search(r"[\\{}%#&$^_~]", font):
            raise BuildError(f"{theme.label}: フォント名 {font!r} に LaTeX の特殊文字が含まれています")
    lines = [f"% {line}" for line in _header(theme, root)]
    lines += [
        "% Usage: \\usepackage{theme-colors}  ->  colors theme-<role>, theme-series-<n>, palette-<name>",
        "\\NeedsTeXFormat{LaTeX2e}",
        f"\\ProvidesPackage{{theme-colors}}[{STY_FORMAT_DATE} design theme {theme.id} {theme.slug}]",
        "\\RequirePackage{xcolor}",
        "",
        "% roles",
    ]
    lines += [define(f"theme-{role}", hex_) for role, hex_ in theme.role_hex().items()]
    if theme.series_names:
        lines += ["", f"% chart.series ({theme.chart_status})"]
        lines += [define(f"theme-series-{i}", hex_) for i, hex_ in enumerate(theme.series_hex(), start=1)]
    lines += ["", "% palette (raw colors; prefer theme-<role>)"]
    lines += [define(f"palette-{name}", hex_) for name, hex_ in theme.palette_hex().items()]
    lines += [
        "",
        "% fonts (e.g. \\setsansfont{\\ThemeLatinFont} with fontspec)",
        f"\\newcommand*{{\\ThemeLatinFont}}{{{typo['latin']}}}",
        f"\\newcommand*{{\\ThemeEastAsianFont}}{{{typo['east_asian']}}}",
        "",
        "\\endinput",
    ]
    return "\n".join(lines) + "\n"


def render_claude_tokens(theme: tl.Theme) -> str:
    typo = theme.typography
    generics = [n for n in tl.font_stack(typo) if n in tl.GENERIC_FONT_FAMILIES] or ["sans-serif"]
    color_tokens = [
        {"name": role, "value": hex_, "usage": theme.roles[role]["usage"]} for role, hex_ in theme.role_hex().items()
    ]
    for i, (name, hex_) in enumerate(zip(theme.series_names, theme.series_hex()), start=1):
        color_tokens.append(
            {
                "name": f"chart-series-{i}",
                "value": hex_,
                "usage": f"グラフ系列色 {i}（{name}、{CHART_STATUS_JA[theme.chart_status]}）",
            }
        )
    doc = {
        "name": theme.label,
        "version": 1,
        "color": {"themes": [{"id": "light", "name": "Light"}], "tokens": color_tokens},
        "type": {
            "fonts": [],
            "families": {"sans": tl.css_font_family([typo["latin"], typo["east_asian"], generics[0]])},
            "groups": [],
        },
    }
    names = [t["name"] for t in color_tokens] + list(doc["type"]["families"])
    bad = [n for n in names if not TOKEN_NAME_RE.match(n)]
    dup = sorted({n for n in names if names.count(n) > 1})
    if bad or dup:
        raise BuildError(f"{theme.label}: Claude 用トークン名が不正です（形式違反: {bad}、重複: {dup}）")
    return _json(doc)


def render_svg(theme: tl.Theme) -> str:
    c = theme.role_hex()
    roles = list(theme.roles)
    series = list(zip(theme.series_names, theme.series_hex()))
    typo = theme.typography
    font = xml_escape(tl.css_font_family([typo["latin"], *typo["fallbacks"]["latin"]]), {'"': "&quot;"})

    width, pad, band_h, row_h = 720, 24, 64, 40
    sw_w, sw_h = 48, 28
    col_w = (width - 2 * pad) // 2
    per_col = math.ceil(len(roles) / 2)
    top = band_h + 20
    rows_bottom = top + per_col * row_h
    series_top = rows_bottom + 8
    height = (series_top + 24 + sw_h + 20 + pad) if series else (rows_bottom + pad - 12)

    def text(x: int, y: int, body: str, size: int, fill: str, extra: str = "") -> str:
        return f'  <text x="{x}" y="{y}" font-size="{size}" fill="{fill}"{extra}>{xml_escape(body)}</text>'

    def rect(x: int, y: int, w: int, h: int, fill: str) -> str:
        return f'  <rect x="{x}.5" y="{y}.5" width="{w - 1}" height="{h - 1}" rx="3" fill="{fill}" stroke="{c["placeholder-border"]}"/>'

    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" font-family="{font}" role="img">',
        f"  <title>{xml_escape(theme.label)} — role swatches</title>",
        f'  <rect width="{width}" height="{height}" fill="{c["background"]}"/>',
        f'  <rect width="{width}" height="{band_h}" fill="{c["band"]}"/>',
        text(pad, 41, f"{theme.id}  {theme.name}", 22, c["on-band"], ' font-weight="bold"'),
        text(width - pad, 40, "CATEGORY", 12, c["category"], ' font-weight="bold" text-anchor="end" letter-spacing="1"'),
    ]
    hexes = theme.role_hex()
    for i, role in enumerate(roles):
        x = pad + (i // per_col) * col_w
        y = top + (i % per_col) * row_h
        out.append(rect(x, y, sw_w, sw_h, hexes[role]))
        out.append(text(x + sw_w + 12, y + 12, role, 14, c["text"]))
        out.append(text(x + sw_w + 12, y + 27, f"{hexes[role]} · {theme.roles[role]['color']}", 11, c["text-secondary"]))
    if series:
        out.append(text(pad, series_top + 14, f"chart.series ({theme.chart_status})", 13, c["text"]))
        for i, (name, hex_) in enumerate(series):
            x = pad + i * 96
            out.append(rect(x, series_top + 24, 84, sw_h, hex_))
            out.append(text(x, series_top + 24 + sw_h + 14, f"{i + 1}. {hex_}", 11, c["text-secondary"]))
    out.append(f'  <rect x="0.5" y="0.5" width="{width - 1}" height="{height - 1}" fill="none" stroke="{c["placeholder-border"]}"/>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------- README


def _contrast_cell(result: Optional[tl.ContrastResult]) -> str:
    if result is None:
        return "—"
    ratio = tl.format_ratio(result.ratio)
    vs = f"vs `{result.against}`"
    status = result.status
    if status == "fail":
        return f"**{ratio}** {vs} ⚠ 基準未満"
    if status == "graphic-only":
        return f"{ratio} {vs} ✓ 線・図形 / ⚠ 文字には不可"
    if status == "decorative":
        return f"{ratio} {vs}"
    return f"{ratio} {vs} ✓"


def render_readme_section(themes: List[tl.Theme], specs: Dict[str, tl.RoleSpec], root: Path) -> str:
    lines = [
        README_BEGIN,
        "<!-- この区間は scripts/build.py が themes/*/theme.json から生成する。手で編集しないこと。 -->",
        "",
        "| 番号 | 名前 | slug | 状態 | band / emphasis / accent |",
        "|---|---|---|---|---|",
    ]
    for t in themes:
        h = t.role_hex()
        lines.append(
            f"| `{t.id}` | {md(t.name)} | `{t.slug}` | {t.status} | `{h['band']}` / `{h['emphasis']}` / `{h['accent']}` |"
        )
    for t in themes:
        d = t.dir.relative_to(root).as_posix()
        typo = t.typography
        results = tl.contrast_results(t, specs)
        by_subject = {r.subject: r for r in results}
        hexes = t.role_hex()
        lines += ["", f"### {t.id} {md(t.name)}", ""]
        if t.status == "deprecated":
            lines += ["> **deprecated**: 新しいプロジェクトでは使わない。", ""]
        lines += [
            f"![{md(t.label)} の色見本](dist/{t.id}/swatches.svg)",
            "",
            f"- slug: `{t.slug}` / 状態: `{t.status}`",
            f"- 出典: {md(t.data['source'])}",
            f"- フォント: 欧文 {typo['latin']}（代替: {', '.join(typo['fallbacks']['latin'])}）、"
            f"和文 {typo['east_asian']}（代替: {', '.join(typo['fallbacks']['east_asian'])}）",
            f"- 使い方のルール: [{d}/README.md]({d}/README.md) ・ 正本: [{d}/theme.json]({d}/theme.json) ・ 生成物: [dist/{t.id}/](dist/{t.id}/)",
            "",
            "| role | palette | hex | 使われ方 | 検査 | コントラスト |",
            "|---|---|---|---|---|---|",
        ]
        for role, spec in t.roles.items():
            lines.append(
                f"| `{role}` | `{spec['color']}` | `{hexes[role]}` | {md(spec['usage'])} | {KIND_JA[specs[role].kind]} "
                f"| {_contrast_cell(by_subject.get(role))} |"
            )
        lines += ["", f"**グラフ系列色（`chart.series`）: {CHART_STATUS_JA[t.chart_status]}**", ""]
        if t.series_names:
            for i, (name, hex_) in enumerate(zip(t.series_names, t.series_hex())):
                lines.append(f"{i + 1}. `{name}` `{hex_}` — {_contrast_cell(by_subject[f'chart.series[{i}]'])}")
        else:
            lines.append("未定義")
        warnings = [r for r in results if r.is_warning]
        lines += ["", "**コントラスト警告**（元資料の値は変更していない）", ""]
        lines += [f"- ⚠ {r.describe()}" for r in warnings] if warnings else ["- なし"]
    lines += ["", README_END]
    return "\n".join(lines)


def md(text: str) -> str:
    return tl.md_escape(text)


def render_readme(current: str, section: str) -> str:
    begin, end = current.find(README_BEGIN), current.find(README_END)
    if begin < 0 or end < begin:
        raise BuildError(f"README.md に {README_BEGIN} と {README_END} の区間がありません")
    return current[:begin] + section + current[end + len(README_END) :]


# --------------------------------------------------------------------------- driver


def render_all(root: Path) -> Dict[str, str]:
    """生成するファイル（リポジトリ直下からの相対パス → 内容）を返す。"""
    errors = [f for f in check.run_checks(root) if f.level == "error"]
    if errors:
        detail = "\n".join(f"  {f.where}: {f.message}" for f in errors)
        raise BuildError(f"check でエラーがあるため生成できません:\n{detail}")
    specs = tl.role_specs_from_schema(tl.load_schema(root))
    themes = tl.load_themes(root)
    outputs: Dict[str, str] = {}
    for t in themes:
        base = f"{tl.DIST_DIRNAME}/{t.id}"
        outputs[f"{base}/tokens.css"] = render_css(t, root)
        outputs[f"{base}/tokens.json"] = render_tokens_json(t, root)
        outputs[f"{base}/theme.mplstyle"] = render_mplstyle(t, root)
        outputs[f"{base}/theme_colors.py"] = render_python(t, root)
        outputs[f"{base}/theme-colors.sty"] = render_sty(t, root)
        outputs[f"{base}/claude-design-system/tokens.json"] = render_claude_tokens(t)
        outputs[f"{base}/swatches.svg"] = render_svg(t)
    readme = root / "README.md"
    if not readme.is_file():
        raise BuildError("README.md がありません")
    outputs["README.md"] = render_readme(tl.read_text(readme), render_readme_section(themes, specs, root))
    return outputs


def _existing_dist_files(root: Path) -> List[str]:
    return [p.relative_to(root).as_posix() for p in tl.list_files(root / tl.DIST_DIRNAME)]


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="theme.json から dist/ と README のテーマ一覧を生成する")
    parser.add_argument("--check", action="store_true", help="書き込まずに、最新かどうかだけ確かめる")
    parser.add_argument("--root", type=Path, default=tl.ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = args.root.resolve()

    try:
        outputs = render_all(root)
    except BuildError as e:
        print(f"build: {e}", file=sys.stderr)
        return 1

    changed = [p for p, content in outputs.items() if not (root / p).is_file() or tl.read_text(root / p) != content]
    stale = [p for p in _existing_dist_files(root) if p not in outputs]

    if args.check:
        for p in changed:
            print(f"build --check: 最新ではありません: {p}")
        for p in stale:
            print(f"build --check: 不要なファイルがあります: {p}")
        if changed or stale:
            print("build --check: python scripts/build.py を実行して、差分をコミットしてください", file=sys.stderr)
            return 1
        print(f"build --check: {len(outputs)} ファイルはすべて最新です")
        return 0

    for p in changed:
        tl.write_text(root / p, outputs[p])
    for p in stale:
        (root / p).unlink()
    dist = root / tl.DIST_DIRNAME
    if dist.is_dir():
        for d in sorted((p for p in dist.rglob("*") if p.is_dir()), key=lambda p: len(p.parts), reverse=True):
            if not any(d.iterdir()):
                d.rmdir()
    print(f"build: {len(outputs)} ファイル中 {len(changed)} 件を更新、{len(stale)} 件を削除")
    return 0


if __name__ == "__main__":
    sys.exit(main())
